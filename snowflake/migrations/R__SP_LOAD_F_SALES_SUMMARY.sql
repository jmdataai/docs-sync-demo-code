CREATE OR REPLACE PROCEDURE SP_LOAD_F_SALES_SUMMARY()
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
BEGIN
    TRUNCATE TABLE F_SALES_SUMMARY;
    COPY INTO F_SALES_SUMMARY (SALE_DT, CITY_NM, REGION_CD, CUSTOMER_SEGMENT, ORDER_CNT, NET_REVENUE_AMT, DISCOUNT_AMT)
    FROM @GOLD_STAGE/f_sales/
    FILE_FORMAT = (TYPE = PARQUET)
    MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;
    RETURN 'loaded';
END;
$$;
