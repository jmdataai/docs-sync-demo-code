-- Gold tables for the Sales Insights product

CREATE TABLE IF NOT EXISTS D_REGION (
    REGION_CD     VARCHAR(10) NOT NULL,
    REGION_NM     VARCHAR(50),
    ACTIVE_FLG    VARCHAR(1) DEFAULT 'Y'
);

CREATE TABLE IF NOT EXISTS F_SALES_SUMMARY (
    SALE_DT           DATE NOT NULL,
    CITY_NM           VARCHAR(50),
    REGION_CD         VARCHAR(10),
    CUSTOMER_SEGMENT  VARCHAR(30),
    ORDER_CNT         NUMBER(18,0),
    NET_REVENUE_AMT   NUMBER(18,2)
)
CLUSTER BY (SALE_DT);
